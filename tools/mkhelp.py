#!/usr/bin/env python3
"""Generate fw/help.c: the line under the menu that says what the lit item does, packed.

    python3 tools/mkhelp.py            # after changing HELP; same order as mnames in fw/main.c

Each line fits the screen (21 characters) and uses only A-Z, space, / and ', five bits a
character, three to a 16-bit word, so 43 lines take about 560 bytes instead of 840. menu_help() in main.c unpacks one, in lower case.
"""
import os

HELP = [  # in menu order: plain words for someone who has never used a two-way radio
    'SIGNAL NEEDED TO HEAR', 'CUTS STRONG SIGNALS', 'LESS HISS IF BOTH ON', 'NARROW CHANNEL WIDTH', 'WIDE OR NARROW VOICE', 'FM AM OR USB SIDEBAND', 'TUNING STEP SIZE', 'HEAR ONLY THIS TONE',
    'TRANSMIT POWER', 'SEND ABOVE OR BELOW', 'REPEATER OFFSET SIZE', 'TONE SENT TO REPEATER', 'BANDS YOU MAY SEND ON',
    'STOPS LONG TRANSMITS', 'ENDS CALLS QUIETLY', 'MICROPHONE LOUDNESS', 'SEND WHEN YOU SPEAK', 'STAYS ON AFTER SPEECH', 'TOUCH TONES TO SEND', 'SENDS YOUR CALLSIGN',
    'CHANNELS TO SCAN', 'MOST TIME ON A SIGNAL', 'WAIT AFTER IT STOPS', 'LISTEN TO A AND B', 'CHECK A CHANNEL OFTEN',
    'SCAN SEVERAL GROUPS', "THIS CHANNEL'S GROUPS",
    'SEE BUSY FREQUENCIES', 'FIND A NEARBY RADIO', 'BROADCAST FM RADIO', 'NOAA WEATHER RADIO', 'RECENT STATIONS HEARD',
    'NAME THIS CHANNEL', 'COPY TO FREQ MODE', 'DELETE A CHANNEL',
    'SCREEN LIGHT TIME', 'SCREEN BRIGHTNESS', 'SCREEN COLOURS', 'LOOK OF BIG NUMBERS', 'SOUND ON KEY PRESS', 'WHAT THE LOCK STOPS', 'DING WHEN CALLED', 'WATCH FOR STORM ALERT',
    'TURN OFF WHEN IDLE', 'LONGER BATTERY LIFE',
    'TALK TO A COMPUTER', 'COMPUTER CONTROLS IT', 'BLUETOOTH ON OR OFF', 'FREQUENCY TRIM', 'SIGNAL METER TRIM', 'BATTERY READING TRIM',
    'FIRMWARE VERSION',
]
CODE = {' ': 27, '/': 28, "'": 29}   # 0 ends a line, 1-26 are A-Z


def pack(lines):
    syms = []
    for s in lines:
        assert len(s) <= 21, s
        syms += [CODE.get(c) or ord(c) - 64 for c in s] + [0]
        assert all(0 <= v < 32 for v in syms), s
    syms += [0] * (-len(syms) % 3)
    return [syms[i] | syms[i + 1] << 5 | syms[i + 2] << 10   # three to a 16-bit word, low bits first
            for i in range(0, len(syms), 3)]


if __name__ == '__main__':
    data = pack(HELP)
    rows = [', '.join('0x%04X' % w for w in data[i:i + 8]) for i in range(0, len(data), 8)]
    src = ('// Generated by tools/mkhelp.py: edit HELP there and rerun. %d lines, %d bytes.\n'
           '#include "fw.h"\n\n'
           'const __code uint16_t menu_help_bits[%d] = {\n    %s,\n};\n') % (len(HELP), 2 * len(data), len(data), ',\n    '.join(rows))
    open(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'fw', 'help.c'), 'w').write(src)
    print('fw/help.c: %d lines, %d bytes' % (len(HELP), 2 * len(data)))
