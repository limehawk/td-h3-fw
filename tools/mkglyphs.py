#!/usr/bin/env python3
"""Generate fw/glyphs.c: the 8x8 icons the screens use, from Open Iconic as u8g2 ships it.

    python3 tools/mkglyphs.py DIR      # DIR holds open_iconic_all_1x.bdf:
    https://raw.githubusercontent.com/olikraus/u8g2/master/tools/font/bdf/open_iconic_all_1x.bdf

Licence: docs/FONTS.md. To add an icon, add its Open Iconic name to ICONS and rerun.
"""
import os, re, sys

ICONS = [('lock', 'lock-locked'), ('bt', 'bluetooth'), ('warn', 'warning'), ('note', 'musical-note'),
         ('pulse', 'pulse'), ('target', 'target'), ('link', 'link-intact'), ('bell', 'bell')]   # (name in C, Open Iconic name)

src = open(os.path.join(sys.argv[1], 'open_iconic_all_1x.bdf')).read()
asc = int(re.search(r'FONT_ASCENT (\d+)', src).group(1))
glyphs = {}
for m in re.finditer(r'STARTCHAR \S*/([\w-]+)\.png\n(.*?)ENDCHAR', src, re.S):
    b = m.group(2)
    w, h, xo, yo = map(int, re.search(r'BBX (-?\d+) (-?\d+) (-?\d+) (-?\d+)', b).group(1, 2, 3, 4))
    rows = [int(r, 16) for r in b.split('BITMAP\n')[1].split()]
    glyphs[m.group(1)] = {(xo + i, asc - (yo + h) + j) for j, r in enumerate(rows) for i in range(w) if r >> ((w + 7) // 8 * 8 - 1 - i) & 1}

out = ['// Generated by tools/mkglyphs.py; do not edit. Open Iconic, licence in docs/FONTS.md.',
       '#include "fw.h"', '', '// width, height, then one byte per row (MSB = left), cropped to the ink.']
for cname, name in ICONS:
    p = glyphs[name]
    x0 = min(x for x, _ in p); y0 = min(y for _, y in p)
    w = max(x for x, _ in p) - x0 + 1; h = max(y for _, y in p) - y0 + 1
    rows = [sum(0x80 >> x for x in range(w) if (x0 + x, y0 + y) in p) for y in range(h)]
    out.append('const __code uint8_t icon_%s[] = {%d, %d, %s};' % (cname, w, h, ','.join('0x%02X' % r for r in rows)))
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'fw', 'glyphs.c'), 'w').write('\n'.join(out) + '\n')
